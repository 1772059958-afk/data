def set_font(run, size: float, *, bold: bool = False, colour: RGBColor = INK) -> None:
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = colour
    run.font.name = FONT
    rpr = run._element.get_or_add_rPr()
    font = rpr.find(qn("w:rFonts"))
    if font is None:
        font = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(font)
    for attr in ("w:ascii", "w:hAnsi", "w:eastAsia", "w:cs"):
        font.set(qn(attr), FONT)


def para(doc, text: str, *, size: float = 11.0, bold: bool = False,
         colour: RGBColor = INK, space_after: float = 6.0):
    paragraph = doc.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(space_after)
    paragraph.paragraph_format.line_spacing = 1.3
    run = paragraph.add_run(text)
    set_font(run, size, bold=bold, colour=colour)
    return paragraph


def heading(doc, text: str, size: float, colour: RGBColor = BLUE,
            space_before: float = 14.0, space_after: float = 4.0):
    paragraph = doc.add_paragraph()
    paragraph.paragraph_format.space_before = Pt(space_before)
    paragraph.paragraph_format.space_after = Pt(space_after)
    run = paragraph.add_run(text)
    set_font(run, size, bold=True, colour=colour)
    return paragraph


